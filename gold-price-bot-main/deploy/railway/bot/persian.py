# ابزار نمایش فارسی: تاریخ و شناسه‌ها فارسی می‌مانند
# ⚠️ قیمت‌ها طبق تصمیم علی با ارقام انگلیسی نمایش داده می‌شوند → money()
FA_DIGITS = str.maketrans("0123456789,.%", "۰۱۲۳۴۵۶۷۸۹٬٫٪")


def fa_digits(value) -> str:
    """هر عدد/رشته‌ای را با ارقام فارسی برمی‌گرداند — برای تاریخ، آی‌دی و شمارنده‌ها"""
    return str(value).translate(FA_DIGITS)


def money(amount: int) -> str:
    """عدد صحیح → جداکننده هزارگان با ارقام انگلیسی (واحد تومان جداگانه اضافه می‌شود):
    95340000 → 95,340,000"""
    return f"{int(amount):,}"
